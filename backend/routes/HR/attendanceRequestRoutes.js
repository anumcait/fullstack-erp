const express = require('express');
const router = express.Router();
const { requirePermission } = require('../../middleware/auth');
const { HR_PERMISSIONS } = require('../../constants/permissions');
const c = require('../../controllers/HR/attendanceRequestController');
router.post('/create', requirePermission(HR_PERMISSIONS.ATTENDANCE_REQUEST), c.createRequest);
router.post('/bulk', requirePermission(HR_PERMISSIONS.ATTENDANCE_REQUEST), c.createBulkRequests);
router.get('/my', c.getMyRequests);
router.get('/pending', requirePermission(HR_PERMISSIONS.ATTENDANCE_APPROVE), c.getPending);
router.get('/all', requirePermission(HR_PERMISSIONS.ATTENDANCE_APPROVE), c.getAllRequests);
router.post('/approve', requirePermission(HR_PERMISSIONS.ATTENDANCE_APPROVE), c.approve);
router.post('/reject', requirePermission(HR_PERMISSIONS.ATTENDANCE_APPROVE), c.reject);
router.put('/:id', requirePermission(HR_PERMISSIONS.ATTENDANCE_REQUEST), c.updateRequest);
router.post('/cancel', c.cancel);
router.post('/bulk-approve', requirePermission(HR_PERMISSIONS.ATTENDANCE_APPROVE), c.bulkApprove);
module.exports = router;
